  static BlockPos home(int slot) {
    // Separate negative-Z bank: active v25 saves keep their original positive-Z 192-block slots.
    return new BlockPos((slot % 4096) * SLOT_WIDTH, 80, -1000000 - (slot / 4096) * SLOT_WIDTH);
  }

