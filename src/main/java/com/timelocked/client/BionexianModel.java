  private ModelPart part(String name) {
    return this.body.hasChild(name) ? this.body.getChild(name) : null;
  }

  public void setupAnim(T entity, float swing, float amount, float age, float yaw, float pitch) {
    this.root.getAllParts().forEach(ModelPart::resetPose);
    ModelPart head = this.part("head");
    head.yRot = yaw * (float) (Math.PI / 180.0);
    head.xRot = pitch * (float) (Math.PI / 180.0);
    float step = Mth.cos(swing * 0.6662F) * amount;
    this.part("leg_a").xRot = step;
    this.part("leg_b").xRot = -step;
    ModelPart armA = this.part("arm_a");
    ModelPart armB = this.part("arm_b");
    armA.xRot = -step * 0.8F;
    armB.xRot = step * 0.8F;
    if (entity.isAggressive()) {
      armA.xRot -= 0.8F;
      armB.xRot -= 0.8F;
    }

    float attack = Mth.sin(entity.getAttackAnim(0.0F) * (float) Math.PI);
    armA.xRot -= attack;
    armB.xRot -= attack;
    ModelPart tail = this.part("tail_base");
    if (tail != null) {
      tail.yRot = Mth.sin(age * 0.09F) * 0.2F;
      if (tail.hasChild("tail_tip")) {
        tail.getChild("tail_tip").yRot = Mth.sin(age * 0.09F + 0.5F) * 0.25F;
      }
    }

    ModelPart earA = head.hasChild("ear_a") ? head.getChild("ear_a") : null;
    ModelPart earB = head.hasChild("ear_b") ? head.getChild("ear_b") : null;
    if (earA != null && earB != null) {
      float flop = Mth.sin(age * 0.07F) * 0.05F + amount * 0.15F;
      earA.zRot += flop;
      earB.zRot -= flop;
    }
  }
